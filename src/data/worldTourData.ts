export function getAllCountries() {
  return seasons.flatMap((s) => s.countries);
}

export function getCountriesBySeasons(activeSeasonIds: Set<number>) {
  return seasons
    .filter((s) => activeSeasonIds.has(s.id))
    .flatMap((s) => s.countries);
}

export function getSeasonColor(seasonId: number): string {
  return seasons.find((s) => s.id === seasonId)?.color ?? '#ffffff';
}

export function getSeasonGlow(seasonId: number): string {
  return seasons.find((s) => s.id === seasonId)?.glowColor ?? 'rgba(255,255,255,0.4)';
}
